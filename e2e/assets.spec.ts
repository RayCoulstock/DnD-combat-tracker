import {multiplayerMode,library,chooseCampaign,openSetup,closeSetup} from './shell-helpers'
import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { makeTexturedGlb } from '../test-fixtures/glb'
test('DM asset upload, metadata search, isolated preview, errors and deletion', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/'); await multiplayerMode(page)
  await expect(page.getByRole('button', { name: 'Libraries', exact: true })).toHaveCount(0)
  await page.getByLabel('Email', { exact: true }).fill(`asset-${randomUUID()}@example.test`)
  await page.getByLabel('Password (12+ characters)', { exact: true }).fill('Browser Asset Password 2049!')
  await page.getByRole('button', { name: 'Create account', exact: true }).click();await openSetup(page)
  await page.getByLabel('New campaign', { exact: true }).fill('Asset preview campaign')
  await page.getByRole('button', { name: 'Create campaign', exact: true }).click()
  await page.getByLabel('New encounter', { exact: true }).fill('Keep this battlefield')
  await page.getByRole('button', { name: 'Create / import encounter', exact: true }).click();await closeSetup(page)
  await page.getByRole('button', { name: 'Battle map', exact: true }).click()
  const encounterCanvas = page.locator('canvas:visible'), encounterElement = await encounterCanvas.elementHandle()
  await library(page,'3D Asset Library')
  await expect(page.getByText('No assets yet. Upload your first GLB model.')).toBeVisible()
  await page.getByLabel('GLB file', { exact: false }).setInputFiles({ name: 'meshy-chair.glb', mimeType: 'model/gltf-binary', buffer: await makeTexturedGlb() })
  await page.getByLabel('Upload asset name', { exact: true }).fill('Meshy oak chair')
  await page.getByLabel('Upload asset category', { exact: true }).selectOption('furniture')
  await page.getByLabel('Upload asset tags (comma separated)', { exact: true }).fill('oak,tavern')
  // Pause the model response to make the loading indicator observable.
  let releaseFile!: () => void
  const fileGate = new Promise<void>(resolve => { releaseFile = resolve })
  await page.route('**/api/assets/*/file', async route => { await fileGate; await route.continue() })
  await page.getByRole('button', { name: 'Upload model', exact: true }).click()
  await expect(page.getByText('Model validated and uploaded.', { exact: true })).toBeVisible()
  await expect(page.getByText('Loading model preview…', { exact: true })).toBeVisible()
  releaseFile()
  const preview = page.getByRole('region', { name: '3D asset preview', exact: true })
  await expect(preview.locator('canvas')).toBeVisible()
  const canvas = preview.locator('canvas'); await canvas.scrollIntoViewIfNeeded()
  const defaultView = await canvas.screenshot(), box = (await canvas.boundingBox())!
  await page.mouse.move(box.x + box.width * .4, box.y + box.height * .4)
  await page.mouse.down(); await page.mouse.move(box.x + box.width * .65, box.y + box.height * .55, { steps: 15 }); await page.mouse.up()
  await page.waitForTimeout(1000)
  expect((await canvas.screenshot()).equals(defaultView)).toBe(false)
  const rotated = await canvas.screenshot()
  await page.mouse.wheel(0, -300)
  await page.waitForTimeout(600)
  expect((await canvas.screenshot()).equals(rotated)).toBe(false)
  await preview.getByRole('button', { name: 'Reset preview camera', exact: true }).click()
  await page.screenshot({ path: '/tmp/asset-library.png', fullPage: true })
  const details = page.getByRole('region', { name: 'Asset details', exact: true })
  await details.getByLabel('Edit asset name', { exact: true }).fill('Tavern chair')
  await details.getByLabel('Edit asset description', { exact: true }).fill('Reusable Meshy export')
  await details.getByLabel('Edit asset category', { exact: true }).selectOption('decoration')
  await details.getByLabel('Default scale', { exact: true }).fill('20')
  await details.getByLabel('Default rotation (degrees)', { exact: true }).fill('90')
  await details.getByRole('button', { name: 'Save asset metadata', exact: true }).click()
  await expect(details.getByRole('heading', { name: 'Tavern chair', exact: true })).toBeVisible()
  await expect(preview.locator('canvas')).toBeVisible() // Large presentation scales are automatically reframed.
  await page.getByLabel('Filter category', { exact: true }).selectOption('miniature')
  await expect(page.getByText('No matching assets.', { exact: true })).toBeVisible()
  await page.getByLabel('Filter category', { exact: true }).selectOption('decoration')
  await page.getByLabel('Search assets', { exact: true }).fill('missing model')
  await page.getByRole('button', { name: 'Search library', exact: true }).click()
  await expect(page.getByText('No matching assets.', { exact: true })).toBeVisible()
  await page.getByLabel('Search assets', { exact: true }).fill('tavern')
  await page.getByRole('button', { name: 'Search library', exact: true }).click()
  await expect(page.locator('.asset-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Return to encounter', exact: true }).click()
  await expect(encounterCanvas).toBeVisible()
  expect(await encounterElement!.evaluate(el => el.isConnected)).toBe(true)
  await library(page,'3D Asset Library')
  await page.reload(); await library(page,'3D Asset Library')
  // Merely browsing the grid must not download every model.
  let modelRequests = 0
  page.on('request', req => { if (/\/api\/assets\/[^/]+\/file$/.test(req.url())) modelRequests++ })
  await expect(page.locator('.asset-card')).toHaveCount(1)
  expect(modelRequests).toBe(0)
  await page.unroute('**/api/assets/*/file')
  await page.route('**/api/assets/*/file', route => route.fulfill({ status: 503, body: 'Unavailable' }))
  await page.locator('.asset-card').click()
  await expect(page.getByRole('alert')).toContainText('Preview failed')
  await page.unroute('**/api/assets/*/file')
  await page.getByRole('button', { name: 'Return to encounter', exact: true }).click()
  // DM campaign choice is intentionally local state and is reset by a full page reload.
  await chooseCampaign(page,{ label: 'Asset preview campaign' })
  await expect(page.getByRole('combobox',{name:'Encounter',exact:true}).locator('option:checked')).toHaveText('Keep this battlefield')
  await library(page,'3D Asset Library')
  await page.locator('.asset-card').click(); await expect(preview.locator('canvas')).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Delete asset', exact: true }).click()
  await expect(page.getByText('Asset deleted.', { exact: true })).toBeVisible()
  await expect(page.getByText('No assets yet. Upload your first GLB model.', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
