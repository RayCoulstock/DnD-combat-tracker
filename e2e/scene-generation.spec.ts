import { test, expect, type Page } from '@playwright/test'
import { sessionAction } from './shell-helpers'
async function exported(page: Page) {
  const download = page.waitForEvent('download')
  await sessionAction(page, 'Export encounter')
  const stream = await (await download).createReadStream(), chunks: Buffer[] = []
  for await (const chunk of stream) chunks.push(Buffer.from(chunk))
  const data = JSON.parse(Buffer.concat(chunks).toString())
  delete data.exportedAt
  return data
}
test('presets, editable seeds and local cancel preserve the encounter until explicit acceptance', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Map editor', exact: true }).click()
  const inspector = page.getByRole('complementary', { name: 'Map inspector' })
  await inspector.locator('summary').filter({ hasText: 'Generate dungeon' }).click()
  const before = await exported(page)
  await inspector.getByLabel('Generation preset', { exact: true }).selectOption('cavern')
  await expect(inspector.getByLabel('Theme', { exact: true })).toHaveValue('cavern')
  await inspector.getByLabel('Random seed', { exact: true }).fill('browser-repeat')
  await inspector.getByRole('button', { name: 'Preview dungeon', exact: true }).click()
  await expect(inspector.getByText('Preview only — the encounter has not changed.')).toBeVisible()
  expect(await exported(page)).toEqual(before)
  await inspector.getByRole('button', { name: 'Cancel generation', exact: true }).click()
  expect(await exported(page)).toEqual(before)
  await inspector.getByRole('button', { name: 'Preview dungeon', exact: true }).click()
  await inspector.getByLabel('Random seed', { exact: true }).fill('edited-seed')
  await expect(inspector.getByRole('button', { name: 'Accept generated map', exact: true })).toHaveCount(0)
  await inspector.getByRole('button', { name: 'Preview dungeon', exact: true }).click()
  await inspector.getByRole('button', { name: 'Accept generated map', exact: true }).click()
  const accepted = await exported(page)
  expect(accepted.dungeonMap.name).toContain('edited-seed')
  await inspector.getByRole('button', { name: 'Regenerate with new seed', exact: true }).click()
  await expect(inspector.getByLabel('Random seed', { exact: true })).not.toHaveValue('edited-seed')
  await inspector.getByRole('button', { name: 'Cancel generation', exact: true }).click()
  expect(await exported(page)).toEqual(accepted)
})
test('structured proposals validate locally while scene acceptance waits for real integration', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Map editor', exact: true }).click()
  const inspector = page.getByRole('complementary', { name: 'Map inspector' })
  await inspector.locator('summary').filter({ hasText: 'Generate dungeon' }).click()
  await inspector.getByText('Scene proposal', { exact: true }).click()
  await inspector.getByRole('button', { name: 'Use current generation options', exact: true }).click()
  await inspector.getByRole('button', { name: 'Validate proposal', exact: true }).click()
  await expect(inspector.getByText('Proposal is valid. Preview is required before acceptance.')).toBeVisible()
  await expect(inspector.getByRole('button', { name: 'Preview scene', exact: true })).toBeDisabled()
  await expect(inspector.getByRole('button', { name: 'Accept scene', exact: true })).toHaveCount(0)
  const input = inspector.getByLabel('Structured scene proposal', { exact: true })
  const invalid = JSON.parse(await input.inputValue()); invalid.version = 2
  await input.fill(JSON.stringify(invalid))
  await inspector.getByRole('button', { name: 'Validate proposal', exact: true }).click()
  await expect(inspector.getByText('Proposal is valid. Preview is required before acceptance.')).toHaveCount(0)
  expect((await exported(page)).dungeonMap).toBeUndefined()
})
test('typed B/C browser mocks exercise variant preview, cancel and explicit named acceptance', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(async () => {
    // This harness is only imported by the test; it is not a production entry point.
    const path = '/e2e/fixtures/scene-proposal-harness.tsx'
    const harness = await import(path)
    harness.mount()
  })
  const panel = page.locator('#scene-harness')
  await panel.getByText('Scene proposal', { exact: true }).click()
  await panel.getByRole('button', { name: 'Use selected template as variant', exact: true }).click()
  const proposal = JSON.parse(await panel.getByLabel('Structured scene proposal', { exact: true }).inputValue())
  expect(proposal.source.revision).toBe(4); expect(proposal.fog).toBe('preserve')
  await panel.getByRole('button', { name: 'Preview scene', exact: true }).click()
  await expect(panel.getByRole('button', { name: 'Accept and save new variant', exact: true })).toBeVisible()
  await panel.getByRole('button', { name: 'Cancel scene preview', exact: true }).click()
  let status = JSON.parse((await panel.getByTestId('workflow-state').textContent())!)
  expect(status.commits).toBe(0); expect(status.preview).toBe(false)
  await panel.getByRole('button', { name: 'Preview scene', exact: true }).click()
  await panel.getByLabel('New variant name', { exact: true }).fill('Independent variant')
  await panel.getByRole('button', { name: 'Accept and save new variant', exact: true }).click()
  await expect(panel.getByText('Variant saved as a new template.', { exact: true })).toBeVisible()
  status = JSON.parse((await panel.getByTestId('workflow-state').textContent())!)
  expect(status).toMatchObject({ commits: 1, preview: false, name: 'Independent variant', original: 'stone-dungeon: browser-typed-mock' })
})
